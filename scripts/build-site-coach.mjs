// Build site-coach/ into dist/site-coach/ for deployment.
//
//   node scripts/build-site-coach.mjs
//
// site-coach/ stays the authored source: readable, heavily commented, openable straight from
// disk. This produces the thing visitors actually get.
//
// What it does and why:
//
//   minify css/js    styles.css is 48% comment by weight, and those comments are the design
//                    documentation - they belong in source and nowhere near the wire. esbuild
//                    does the minifying; a regex CSS minifier is a bug farm.
//
//   content hashing  styles.css?v=15 becomes styles.<hash>.css. A query string is NOT a safe
//                    cache key for `immutable`: some intermediaries ignore it, and `immutable`
//                    promises the bytes at a URL never change. Hashing the filename makes that
//                    promise true, which is what lets _headers hand out a year.
//
//   _headers rewrite the immutable block is generated here rather than hand-written, so the
//                    hashed filenames in it can never drift from the ones in the HTML.
//
// Everything else is copied byte for byte.
import { readFile, writeFile, mkdir, rm, readdir, stat, copyFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { join, relative, dirname, extname } from 'node:path'
import { execFileSync } from 'node:child_process'

const SRC = 'site-coach'
const OUT = join('dist', 'site-coach')

const hash8 = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 8)

async function walk (dir, acc = []) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) await walk(p, acc)
    else acc.push(p)
  }
  return acc
}

// esbuild is invoked through the shell: Node on Windows refuses to spawn a .cmd shim directly
// (EINVAL) since the CVE-2024-27980 hardening, and npx resolves to one.
// No --loader: esbuild infers it from the file extension, and passing it explicitly is an
// error for anything but stdin.
function minify (file) {
  return execFileSync(
    process.platform === 'win32' ? 'npx.cmd' : 'npx',
    ['--yes', 'esbuild', file, '--minify'],
    { encoding: 'buffer', shell: process.platform === 'win32', maxBuffer: 32 * 1024 * 1024 }
  )
}

const kib = (n) => (n / 1024).toFixed(1).padStart(6) + ' KiB'

async function main () {
  await rm(OUT, { recursive: true, force: true })
  await mkdir(OUT, { recursive: true })

  const files = await walk(SRC)
  const hashed = {} // source basename -> built basename

  // 1. Hash and minify the two assets every page references.
  for (const name of ['styles.css', 'site.js']) {
    const src = join(SRC, name)
    try { await stat(src) } catch { continue }
    const raw = await readFile(src)
    const min = minify(src)
    const h = hash8(min)
    const ext = extname(name)
    const built = `${name.slice(0, -ext.length)}.${h}${ext}`
    await writeFile(join(OUT, built), min)
    hashed[name] = built
    console.log(`  ${name.padEnd(12)} ${kib(raw.length)} -> ${kib(min.length)}  ${built}`)
  }

  // 2. Copy everything else, rewriting HTML references and _headers as we go.
  let copied = 0
  for (const f of files) {
    const rel = relative(SRC, f)
    const base = rel.split(/[/\\]/).pop()
    if (hashed[base] && !rel.includes('/') && !rel.includes('\\')) continue // originals not shipped
    if (base === 'METRICS.txt') continue // build provenance, not a web asset

    const dest = join(OUT, rel)
    await mkdir(dirname(dest), { recursive: true })

    if (rel.endsWith('.html')) {
      let html = await readFile(f, 'utf8')
      for (const [name, built] of Object.entries(hashed)) {
        // Matches "styles.css?v=15", "../styles.css?v=15" and "/styles.css?v=15" alike,
        // preserving whatever prefix the page used.
        const ext = extname(name)
        const stem = name.slice(0, -ext.length)
        html = html.replace(
          new RegExp(`((?:\\.\\./|/)?)${stem}\\${ext}(\\?v=\\d+)?`, 'g'),
          (_m, prefix) => `${prefix}${built}`
        )
      }
      await writeFile(dest, html)
    } else if (base === '_headers') {
      await writeFile(dest, rewriteHeaders(await readFile(f, 'utf8'), hashed))
    } else {
      await copyFile(f, dest)
      copied++
    }
  }

  console.log(`\n  copied ${copied} other files -> ${OUT}`)
}

function rewriteHeaders (text, hashed) {
  // Drop the old query-string-era cache rules; they named styles.css / site.js, which no
  // longer exist under those names in the build.
  let out = text.replace(/\n\/styles\.css\n[^\n]*\n/, '\n').replace(/\n\/site\.js\n[^\n]*\n/, '\n')
  out = out.replace(/\n\/img\/\*\n[^\n]*\n/, '\n').replace(/\n\/assets\/\*\n[^\n]*\n/, '\n')

  const block = [
    '',
    '# Generated by scripts/build-site-coach.mjs - edit the script, not this block.',
    '#',
    '# A year plus immutable is only safe because these URLs are content-addressed or are',
    '# themselves immutable content: the CSS and JS carry a hash of their own bytes, and a',
    '# change to a font, image or video ships under a new build. Never put a hand-maintained',
    '# filename in here.',
    ...Object.values(hashed).flatMap((built) => [
      `/${built}`,
      '  Cache-Control: public, max-age=31536000, immutable',
    ]),
    '',
    '/fonts/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '/img/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ].join('\n')

  return out.trimEnd() + '\n' + block
}

main().catch((e) => { console.error(e); process.exit(1) })
